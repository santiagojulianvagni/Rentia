-- Eventos comerciales de cada tienda (Hot Sale, Cyber Monday, lanzamientos) para comparar
-- su ganancia contra días normales.
CREATE TABLE IF NOT EXISTS sales_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES accounts(user_id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  start_date TEXT NOT NULL,
  end_date TEXT NOT NULL,
  created_at TEXT NOT NULL,
  CHECK (start_date <= end_date)
);
CREATE INDEX IF NOT EXISTS idx_sales_events_user ON sales_events(user_id, start_date DESC);
