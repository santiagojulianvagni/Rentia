-- Botón de arrepentimiento (Res. 424/2020): pedidos de revocación de la contratación dentro de
-- los 10 días. No requieren cuenta: se identifican con un código de trámite que se entrega al
-- instante y se manda por mail. De la IP se guarda solo una huella, para frenar abusos.
CREATE TABLE IF NOT EXISTS withdrawal_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  store TEXT,
  reason TEXT,
  user_id TEXT REFERENCES accounts(user_id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'received',
  ip_hash TEXT,
  created_at TEXT NOT NULL,
  resolved_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_withdrawal_requests_ip ON withdrawal_requests(ip_hash, created_at);
