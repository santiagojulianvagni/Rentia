-- Locales físicos: cada uno es un canal de venta con sus propios costos. Sus ventas diarias
-- se guardan en external_revenue con store_id; las filas sin store_id siguen siendo la
-- facturación externa de antes (sin costos).
CREATE TABLE IF NOT EXISTS physical_stores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES accounts(user_id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  cost_percent DOUBLE PRECISION NOT NULL DEFAULT 0,
  fee_percent DOUBLE PRECISION NOT NULL DEFAULT 0,
  tax_percent DOUBLE PRECISION NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE(user_id, name)
);
ALTER TABLE external_revenue ADD COLUMN IF NOT EXISTS store_id BIGINT REFERENCES physical_stores(id) ON DELETE CASCADE;
ALTER TABLE external_revenue ADD COLUMN IF NOT EXISTS product_cost DOUBLE PRECISION;
ALTER TABLE external_revenue DROP CONSTRAINT IF EXISTS external_revenue_user_id_revenue_date_key;
CREATE UNIQUE INDEX IF NOT EXISTS uq_external_revenue_store_day ON external_revenue(user_id, COALESCE(store_id, 0), revenue_date);
