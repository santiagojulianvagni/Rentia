-- Mails que manda Rentia (aviso de prueba, cobros, baja, etc.). Cada aviso se registra con una
-- referencia para no mandarlo dos veces aunque la tarea diaria corra de nuevo.
CREATE TABLE IF NOT EXISTS email_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES accounts(user_id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  ref TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  provider_id TEXT,
  error TEXT,
  created_at TEXT NOT NULL,
  sent_at TEXT,
  UNIQUE (user_id, kind, ref)
);
CREATE INDEX IF NOT EXISTS idx_email_log_user ON email_log(user_id, created_at);
