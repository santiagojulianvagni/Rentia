CREATE TABLE meli_ads_accounts (user_id TEXT NOT NULL,seller_id TEXT NOT NULL,advertiser_id TEXT NOT NULL,site_id TEXT NOT NULL,name TEXT NOT NULL,currency TEXT NOT NULL,selected BIGINT NOT NULL DEFAULT 0,last_completed_at TEXT,last_error TEXT,retry_at BIGINT NOT NULL DEFAULT 0,discovered_at TEXT NOT NULL,PRIMARY KEY(user_id,seller_id,advertiser_id),FOREIGN KEY(user_id) REFERENCES accounts(user_id) ON DELETE CASCADE);

CREATE TABLE meli_ads_daily (user_id TEXT NOT NULL,seller_id TEXT NOT NULL,advertiser_id TEXT NOT NULL,campaign_id TEXT NOT NULL,date TEXT NOT NULL,name TEXT NOT NULL,status TEXT NOT NULL,cost_cents BIGINT NOT NULL,attributed_cents BIGINT NOT NULL,clicks BIGINT NOT NULL,impressions BIGINT NOT NULL,units DOUBLE PRECISION NOT NULL,PRIMARY KEY(user_id,seller_id,advertiser_id,campaign_id,date),FOREIGN KEY(user_id) REFERENCES accounts(user_id) ON DELETE CASCADE);

