-- Esquema inicial de Rentia en Postgres (Neon).
-- Equivale al estado final de las 25 migraciones SQLite de drizzle/ (D1).
-- Fechas como TEXT ISO-8601 y flags como 0/1, igual que antes, para no cambiar la lógica.

CREATE TABLE accounts (
  user_id TEXT PRIMARY KEY,
  email TEXT NOT NULL,
  owner_name TEXT NOT NULL,
  store_name TEXT NOT NULL,
  country TEXT NOT NULL DEFAULT 'AR',
  currency TEXT NOT NULL DEFAULT 'ARS',
  trial_started_at TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE store_settings (
  user_id TEXT PRIMARY KEY,
  primary_channel TEXT,
  shipping_cost_ars BIGINT NOT NULL DEFAULT 0,
  commission_percent DOUBLE PRECISION NOT NULL DEFAULT 0,
  tax_percent DOUBLE PRECISION NOT NULL DEFAULT 0,
  onboarding_complete BIGINT NOT NULL DEFAULT 0,
  updated_at TEXT NOT NULL, shipping_mode TEXT NOT NULL DEFAULT 'average', tiendanube_plan_name TEXT, pago_nube_payout_days BIGINT, pago_nube_plan_override TEXT,
  FOREIGN KEY (user_id) REFERENCES accounts(user_id) ON DELETE CASCADE
);

CREATE TABLE oauth_states (
  state TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  provider TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE integrations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL,
  provider TEXT NOT NULL,
  external_store_id TEXT NOT NULL,
  encrypted_access_token TEXT NOT NULL,
  token_iv TEXT NOT NULL,
  scopes TEXT,
  status TEXT NOT NULL DEFAULT 'connected',
  connected_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE(user_id, provider, external_store_id),
  FOREIGN KEY (user_id) REFERENCES accounts(user_id) ON DELETE CASCADE
);

CREATE TABLE app_sessions (
  token_hash TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  created_at TEXT NOT NULL,
  FOREIGN KEY (user_id) REFERENCES accounts(user_id) ON DELETE CASCADE
);

CREATE TABLE products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL,
  provider TEXT NOT NULL,
  external_product_id TEXT NOT NULL,
  name TEXT NOT NULL,
  image_url TEXT,
  published BIGINT NOT NULL DEFAULT 1,
  source_created_at TEXT,
  source_updated_at TEXT,
  synced_at TEXT NOT NULL, rentia_archived BIGINT NOT NULL DEFAULT 0,
  UNIQUE(user_id, provider, external_product_id),
  FOREIGN KEY (user_id) REFERENCES accounts(user_id) ON DELETE CASCADE
);

CREATE TABLE product_variants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL,
  provider TEXT NOT NULL,
  external_product_id TEXT NOT NULL,
  external_variant_id TEXT NOT NULL,
  sku TEXT,
  price DOUBLE PRECISION NOT NULL DEFAULT 0,
  cost DOUBLE PRECISION NOT NULL DEFAULT 0,
  stock BIGINT,
  stock_management BIGINT NOT NULL DEFAULT 0,
  synced_at TEXT NOT NULL, manual_cost DOUBLE PRECISION, manual_cost_updated_at TEXT,
  UNIQUE(user_id, provider, external_variant_id),
  FOREIGN KEY (user_id) REFERENCES accounts(user_id) ON DELETE CASCADE
);

CREATE TABLE orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL,
  provider TEXT NOT NULL,
  external_order_id TEXT NOT NULL,
  order_number TEXT,
  currency TEXT NOT NULL DEFAULT 'ARS',
  status TEXT NOT NULL,
  payment_status TEXT NOT NULL,
  shipping_status TEXT,
  total DOUBLE PRECISION NOT NULL DEFAULT 0,
  subtotal DOUBLE PRECISION NOT NULL DEFAULT 0,
  discount DOUBLE PRECISION NOT NULL DEFAULT 0,
  source_created_at TEXT NOT NULL,
  source_updated_at TEXT,
  synced_at TEXT NOT NULL, payment_method TEXT, source_shipping_cost DOUBLE PRECISION, source_commission_cost DOUBLE PRECISION, source_commission_checked_at TEXT, payment_type TEXT, payment_installments BIGINT, manual_commission_cost DOUBLE PRECISION, meli_post_sale_json TEXT, meli_post_sale_checked_at TEXT, meli_refund_adjustment_json TEXT,
  UNIQUE(user_id, provider, external_order_id),
  FOREIGN KEY (user_id) REFERENCES accounts(user_id) ON DELETE CASCADE
);

CREATE TABLE order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL,
  provider TEXT NOT NULL,
  external_order_id TEXT NOT NULL,
  external_line_id TEXT NOT NULL,
  external_product_id TEXT,
  external_variant_id TEXT,
  name TEXT NOT NULL,
  sku TEXT,
  quantity BIGINT NOT NULL DEFAULT 0,
  unit_price DOUBLE PRECISION NOT NULL DEFAULT 0,
  unit_cost DOUBLE PRECISION NOT NULL DEFAULT 0,
  UNIQUE(user_id, provider, external_order_id, external_line_id),
  FOREIGN KEY (user_id) REFERENCES accounts(user_id) ON DELETE CASCADE
);

CREATE TABLE sync_status (
  user_id TEXT NOT NULL,
  provider TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'idle',
  last_started_at TEXT,
  last_completed_at TEXT,
  last_error TEXT,
  orders_synced BIGINT NOT NULL DEFAULT 0,
  products_synced BIGINT NOT NULL DEFAULT 0, details_version BIGINT NOT NULL DEFAULT 0, webhook_status TEXT NOT NULL DEFAULT 'pending', last_webhook_at TEXT, webhooks_registered_at TEXT, webhook_error TEXT,
  PRIMARY KEY(user_id, provider),
  FOREIGN KEY (user_id) REFERENCES accounts(user_id) ON DELETE CASCADE
);

CREATE TABLE cost_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL,
  category TEXT NOT NULL,
  name TEXT NOT NULL,
  match_value TEXT,
  calculation TEXT NOT NULL,
  amount DOUBLE PRECISION NOT NULL DEFAULT 0,
  percentage DOUBLE PRECISION NOT NULL DEFAULT 0,
  starts_at TEXT,
  ends_at TEXT,
  enabled BIGINT NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  FOREIGN KEY (user_id) REFERENCES accounts(user_id) ON DELETE CASCADE
);

CREATE TABLE external_revenue (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL,
  revenue_date TEXT NOT NULL,
  order_count BIGINT NOT NULL DEFAULT 0,
  revenue DOUBLE PRECISION NOT NULL DEFAULT 0,
  currency TEXT NOT NULL DEFAULT 'ARS',
  updated_at TEXT NOT NULL,
  UNIQUE(user_id, revenue_date),
  FOREIGN KEY (user_id) REFERENCES accounts(user_id) ON DELETE CASCADE
);

CREATE TABLE exchange_rate_settings (
  user_id TEXT PRIMARY KEY,
  rate_type TEXT NOT NULL DEFAULT 'official',
  base_rate DOUBLE PRECISION NOT NULL DEFAULT 0,
  adjustment_percent DOUBLE PRECISION NOT NULL DEFAULT 0,
  updated_at TEXT NOT NULL,
  FOREIGN KEY (user_id) REFERENCES accounts(user_id) ON DELETE CASCADE
);

CREATE TABLE meta_ad_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL,
  external_account_id TEXT NOT NULL,
  name TEXT NOT NULL,
  currency TEXT NOT NULL DEFAULT 'ARS',
  timezone_name TEXT,
  account_status BIGINT NOT NULL DEFAULT 0,
  selected BIGINT NOT NULL DEFAULT 0,
  synced_at TEXT NOT NULL,
  UNIQUE(user_id, external_account_id),
  FOREIGN KEY (user_id) REFERENCES accounts(user_id) ON DELETE CASCADE
);

CREATE TABLE meta_campaigns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL,
  external_account_id TEXT NOT NULL,
  external_campaign_id TEXT NOT NULL,
  name TEXT NOT NULL,
  status TEXT,
  effective_status TEXT,
  daily_budget DOUBLE PRECISION NOT NULL DEFAULT 0,
  lifetime_budget DOUBLE PRECISION NOT NULL DEFAULT 0,
  synced_at TEXT NOT NULL,
  UNIQUE(user_id, external_campaign_id),
  FOREIGN KEY (user_id) REFERENCES accounts(user_id) ON DELETE CASCADE
);

CREATE TABLE meta_insights_daily (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL,
  external_account_id TEXT NOT NULL,
  external_campaign_id TEXT NOT NULL,
  insight_date TEXT NOT NULL,
  spend DOUBLE PRECISION NOT NULL DEFAULT 0,
  impressions BIGINT NOT NULL DEFAULT 0,
  clicks BIGINT NOT NULL DEFAULT 0,
  purchases DOUBLE PRECISION NOT NULL DEFAULT 0,
  purchase_value DOUBLE PRECISION NOT NULL DEFAULT 0,
  synced_at TEXT NOT NULL,
  UNIQUE(user_id, external_account_id, external_campaign_id, insight_date),
  FOREIGN KEY (user_id) REFERENCES accounts(user_id) ON DELETE CASCADE
);

CREATE TABLE dashboard_preferences (
  user_id TEXT PRIMARY KEY,
  layout_json TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  FOREIGN KEY (user_id) REFERENCES accounts(user_id) ON DELETE CASCADE
);

CREATE TABLE store_identity_links (
  store_user_id TEXT PRIMARY KEY,
  clerk_organization_id TEXT NOT NULL UNIQUE,
  owner_clerk_user_id TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  FOREIGN KEY (store_user_id) REFERENCES accounts(user_id) ON DELETE CASCADE
