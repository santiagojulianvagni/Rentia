CREATE TABLE webhook_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider TEXT NOT NULL,
  event_key TEXT NOT NULL UNIQUE,
  user_id TEXT,
  external_store_id TEXT NOT NULL,
  event_type TEXT NOT NULL,
  resource_id TEXT,
