-- Pedidos de privacidad de Tiendanube (LGPD): borrar los datos de una tienda que desinstaló la app,
-- borrar los de un comprador y pedidos de datos de un comprador. Queda registro de qué se pidió y
-- qué hizo Rentia, sin datos personales del comprador.
CREATE TABLE IF NOT EXISTS privacy_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider TEXT NOT NULL,
  store_id TEXT NOT NULL,
  user_id TEXT REFERENCES accounts(user_id) ON DELETE SET NULL,
  kind TEXT NOT NULL,
  external_id TEXT,
  result_json TEXT NOT NULL,
  received_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_privacy_requests_user ON privacy_requests(user_id, received_at);
